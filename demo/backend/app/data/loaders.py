"""Cached, read-only loaders for research artifacts.

The analysis layer under paper/analysis/ is regenerated by another process while the demo
runs. Every cached value is keyed on the mtimes of its source files, so a rebuilt artifact
is picked up on the next request; if a source is briefly missing or half-written, the last
good value is served instead of failing.
"""

from __future__ import annotations

import ast
import json
import logging
import struct
import threading
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any, Callable, Dict, Iterable, List, Optional, Tuple

import pandas as pd

from app.data import paths as P

log = logging.getLogger("wildpalm.loaders")


class _MtimeCache:
    def __init__(self) -> None:
        self._entries: Dict[str, Tuple[tuple, Any]] = {}
        self._locks: Dict[str, threading.Lock] = {}
        self._guard = threading.Lock()

    def _lock(self, key: str) -> threading.Lock:
        with self._guard:
            return self._locks.setdefault(key, threading.Lock())

    @staticmethod
    def _signature(sources: Iterable[Path]) -> tuple:
        sig = []
        for path in sources:
            try:
                sig.append((str(path), path.stat().st_mtime_ns))
            except FileNotFoundError:
                sig.append((str(path), None))
        return tuple(sig)

    def get(self, key: str, sources: List[Path], build: Callable[[], Any]) -> Any:
        with self._lock(key):
            sig = self._signature(sources)
            entry = self._entries.get(key)
            if entry is not None and entry[0] == sig:
                return entry[1]
            try:
                value = build()
            except Exception:
                if entry is not None:
                    log.warning("rebuild of %s failed; serving previous value", key, exc_info=True)
                    return entry[1]
                raise
            self._entries[key] = (sig, value)
            return value


CACHE = _MtimeCache()


def read_csv(path: Path, **kwargs: Any) -> pd.DataFrame:
    key = f"csv:{path}:{sorted(kwargs.items())!r}"
    return CACHE.get(key, [path], lambda: pd.read_csv(path, **kwargs))


def read_json(path: Path) -> Any:
    return CACHE.get(f"json:{path}", [path], lambda: json.loads(path.read_text()))


def analysis_csv(*parts: str, **kwargs: Any) -> Optional[pd.DataFrame]:
    path = P.ANALYSIS_OUT.joinpath(*parts)
    if not path.is_file():
        return None
    return read_csv(path, **kwargs)


# ---------------------------------------------------------------------------
# Analysis-layer registry (paper/analysis/scripts/common.py), parsed statically.
# The module is never imported or executed: only literal assignments are read.
# ---------------------------------------------------------------------------
_RUN_ARGS = ("model_key", "display", "family", "nominal_size", "nominal_b", "rel", "checkpoint", "expected")
_REGISTRY_NAMES = ("LADDERS", "CORE_PANEL", "PAIR_GROUPS", "PAIR_GROUP_NOTES", "NOT_RUN",
                   "CONDITION_POLICY", "KNOWN_EXCLUSIONS")


def _parse_common() -> Dict[str, Any]:
    tree = ast.parse(P.COMMON_PY.read_text())
    out: Dict[str, Any] = {"RUNS": []}
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        name = target.id
        if name == "RUNS" and isinstance(node.value, ast.List):
            for call in node.value.elts:
                if not (isinstance(call, ast.Call) and getattr(call.func, "id", None) == "_run"):
                    continue
                try:
                    values = [ast.literal_eval(a) for a in call.args]
                    kw = {k.arg: ast.literal_eval(k.value) for k in call.keywords}
                except ValueError:
                    continue
                run = dict(zip(_RUN_ARGS, values))
                run["eval_key"] = kw.get("eval_key", run.get("model_key"))
                out["RUNS"].append(run)
        elif name in _REGISTRY_NAMES:
            try:
                out[name] = ast.literal_eval(node.value)
            except ValueError:
                log.warning("could not parse %s from common.py", name)
    return out


def analysis_registry() -> Dict[str, Any]:
    return CACHE.get("registry", [P.COMMON_PY], _parse_common)


